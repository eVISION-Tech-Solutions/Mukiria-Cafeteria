create or replace function public.create_order(p_phone_number text, p_items jsonb)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_item jsonb;
  v_meal public.meals%rowtype;
  v_order_id bigint;
  v_total numeric(12, 2) := 0;
  v_date date := timezone('Africa/Nairobi', now())::date;
  v_number integer;
  v_ticket text;
begin
  if p_phone_number !~ '^0[17][0-9]{8}$' then
    raise exception 'Enter a valid Kenyan phone number (e.g. 0712345678 or 0112345678).';
  end if;
  if jsonb_typeof(p_items) <> 'array' or jsonb_array_length(p_items) < 1 or jsonb_array_length(p_items) > 50 then
    raise exception 'At least one item is required.';
  end if;
  if exists (
    select 1 from jsonb_array_elements(p_items) as entry(value)
    group by (value->>'meal_id') having count(*) > 1
  ) then
    raise exception 'Duplicate meals in order are not allowed.';
  end if;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    if coalesce((v_item->>'quantity')::integer, 0) < 1 or (v_item->>'quantity')::integer > 50 then
      raise exception 'Quantity must be between 1 and 50.';
    end if;
    select * into v_meal from public.meals
      where id = (v_item->>'meal_id')::bigint and available = true for share;
    if not found then
      raise exception 'Meal not found or currently unavailable.';
    end if;
    v_total := v_total + v_meal.price * (v_item->>'quantity')::integer;
  end loop;
  if v_total <> trunc(v_total) then
    raise exception 'M-Pesa payments require totals in whole Kenyan shillings.';
  end if;

  insert into public.daily_ticket_counters(ticket_date, last_number)
    values (v_date, 1)
    on conflict (ticket_date) do update set last_number = daily_ticket_counters.last_number + 1
    returning last_number into v_number;
  v_ticket := 'MTTI-' || to_char(v_date, 'YYYYMMDD') || '-' || lpad(v_number::text, 4, '0');

  insert into public.orders(ticket_number, phone_number, total_amount)
    values (v_ticket, p_phone_number, v_total)
    returning id into v_order_id;

  for v_item in select value from jsonb_array_elements(p_items)
  loop
    select * into v_meal from public.meals where id = (v_item->>'meal_id')::bigint;
    insert into public.order_items(order_id, meal_id, meal_name, quantity, unit_price, subtotal)
      values (
        v_order_id, v_meal.id, v_meal.name, (v_item->>'quantity')::integer, v_meal.price,
        v_meal.price * (v_item->>'quantity')::integer
      );
  end loop;
  return v_order_id;
end;
$$;

create or replace function public.collect_order(p_ticket_number text, p_staff_id uuid)
returns bigint
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_order public.orders%rowtype;
begin
  if not exists (select 1 from public.staff_profiles where id = p_staff_id and is_active = true) then
    raise exception 'Staff account is inactive or missing.';
  end if;
  select * into v_order from public.orders
    where upper(ticket_number) = upper(trim(p_ticket_number)) for update;
  if not found then raise exception 'Ticket number not found.'; end if;
  if v_order.payment_status <> 'paid' then raise exception 'Order payment has not been completed.'; end if;
  if v_order.collection_status = 'collected' then raise exception 'This order has already been collected.'; end if;
  update public.orders set collection_status = 'collected', collected_by = p_staff_id,
    collected_at = now(), updated_at = now() where id = v_order.id;
  return v_order.id;
end;
$$;

create or replace function public.process_payment_callback(
  p_checkout_request_id text,
  p_result_code integer,
  p_result_desc text,
  p_receipt text,
  p_amount numeric,
  p_raw_callback jsonb
)
returns boolean
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_payment public.payment_transactions%rowtype;
begin
  select * into v_payment from public.payment_transactions
    where checkout_request_id = p_checkout_request_id for update;
  if not found or v_payment.status <> 'initiated' then return false; end if;
  if p_result_code = 0 and coalesce(p_amount, 0) <> v_payment.amount then
    update public.payment_transactions set status = 'failed', result_code = p_result_code,
      result_desc = 'Callback amount did not match the order amount.', raw_callback = p_raw_callback,
      updated_at = now() where id = v_payment.id;
    return false;
  end if;
  update public.payment_transactions set
    status = case when p_result_code = 0 then 'success' else 'failed' end,
    result_code = p_result_code, result_desc = left(coalesce(p_result_desc, ''), 1000),
    mpesa_receipt = left(coalesce(p_receipt, ''), 32),
    raw_callback = p_raw_callback, updated_at = now()
    where id = v_payment.id;
  if p_result_code = 0 then
    update public.orders set payment_status = 'paid', updated_at = now()
      where id = v_payment.order_id and collection_status = 'uncollected';
  else
    update public.orders set payment_status = 'failed', updated_at = now()
      where id = v_payment.order_id and payment_status = 'pending';
  end if;
  return true;
end;
$$;

create or replace function public.get_report_summary()
returns table(total_orders bigint, total_revenue numeric, paid_orders bigint, pending_orders bigint)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select count(*),
    coalesce(sum(total_amount) filter (where payment_status = 'paid'), 0),
    count(*) filter (where payment_status = 'paid'),
    count(*) filter (where payment_status = 'pending')
  from public.orders;
$$;

create or replace function public.get_sales_report(p_period text)
returns table(period text, revenue numeric)
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
begin
  if p_period not in ('daily', 'weekly', 'monthly', 'yearly') then
    raise exception 'Unsupported sales report period.';
  end if;
  return query
    select to_char(date_trunc(
        case p_period when 'daily' then 'day' when 'weekly' then 'week'
          when 'monthly' then 'month' else 'year' end,
        timezone('Africa/Nairobi', created_at)
      ), case p_period when 'daily' then 'YYYY-MM-DD' when 'weekly' then 'IYYY-"W"IW'
        when 'monthly' then 'YYYY-MM' else 'YYYY' end)::text,
      sum(total_amount)
    from public.orders
    where payment_status = 'paid'
    group by 1 order by 1;
end;
$$;

create or replace function public.get_meal_performance_report()
returns table(name text, sold bigint, revenue numeric)
language sql
stable
security definer
set search_path = public, pg_temp
as $$
  select items.meal_name, sum(items.quantity), sum(items.subtotal)
  from public.order_items items
  join public.orders on orders.id = items.order_id
  where orders.payment_status = 'paid'
  group by items.meal_name
  order by sum(items.quantity) desc;
$$;

