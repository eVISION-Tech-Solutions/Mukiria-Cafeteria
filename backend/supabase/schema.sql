create extension if not exists pgcrypto;

create table if not exists public.staff_profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text not null unique,
  email text not null,
  first_name text not null default '',
  last_name text not null default '',
  role text not null check (role in ('administrator', 'cashier')),
  phone_number text not null default '',
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);
create unique index if not exists staff_profiles_username_ci_idx on public.staff_profiles (lower(username));

create table if not exists public.meals (
  id bigint generated by default as identity primary key,
  name varchar(200) not null,
  description text not null default '',
  category text not null check (category in ('main_meals', 'proteins', 'vegetables', 'drinks', 'snacks', 'desserts')),
  image text,
  price numeric(10, 2) not null check (price > 0),
  available boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists meals_available_category_idx on public.meals (available, category);

create table if not exists public.daily_ticket_counters (
  ticket_date date primary key,
  last_number integer not null default 0 check (last_number >= 0)
);

create table if not exists public.orders (
  id bigint generated by default as identity primary key,
  ticket_number varchar(30) not null unique,
  phone_number varchar(15) not null,
  total_amount numeric(10, 2) not null check (total_amount > 0),
  payment_status text not null default 'pending' check (payment_status in ('pending', 'paid', 'failed')),
  collection_status text not null default 'uncollected' check (collection_status in ('uncollected', 'collected')),
  collected_by uuid references public.staff_profiles(id) on delete set null,
  collected_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists orders_created_at_idx on public.orders (created_at desc);
create index if not exists orders_status_idx on public.orders (payment_status, collection_status);
create index if not exists orders_phone_idx on public.orders (phone_number);

create table if not exists public.order_items (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  meal_id bigint not null references public.meals(id) on delete restrict,
  meal_name varchar(200) not null,
  quantity integer not null check (quantity between 1 and 50),
  unit_price numeric(10, 2) not null check (unit_price > 0),
  subtotal numeric(12, 2) not null check (subtotal > 0)
);
create index if not exists order_items_order_meal_idx on public.order_items (order_id, meal_id);

create table if not exists public.payment_transactions (
  id bigint generated by default as identity primary key,
  order_id bigint not null references public.orders(id) on delete cascade,
  checkout_request_id text unique,
  merchant_request_id text,
  mpesa_receipt varchar(32) not null default '',
  amount numeric(10, 2) not null check (amount > 0),
  phone_number varchar(15) not null,
  status text not null default 'initiated' check (status in ('initiated', 'success', 'failed', 'cancelled')),
  result_code integer,
  result_desc text not null default '',
  raw_callback jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index if not exists payment_transactions_order_status_idx on public.payment_transactions (order_id, status);
create unique index if not exists one_initiated_payment_per_order_idx
  on public.payment_transactions (order_id) where status = 'initiated';

